import { readFileSync, writeFileSync } from "node:fs";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { Schema } from "effect";
import { responseSchemas } from "../app/modules/http/server.ts";

const outDir = new URL("../app/modules/sdk/lib/generated/", import.meta.url);
const header = "// Generated by scripts/generate-validators.ts from the backend's response Schemas. Do not edit.\n";

const entries = Object.entries(responseSchemas).flatMap(([module, schemas]) =>
  Object.entries(schemas).map(([name, schema]) => ({ module, name, schema })),
);

const ajv = new Ajv2020({ code: { source: true, esm: true, lines: true }, strict: true, allErrors: false });
for (const { name, schema } of entries) {
  const document = Schema.toJsonSchemaDocument(schema);
  ajv.addSchema({ ...document.schema, $defs: document.definitions }, name);
}

const exportsByName = Object.fromEntries(entries.map(({ name }) => [`is${name}`, name]));
const javascript = `${header}${standaloneCode(ajv, exportsByName)}\n`;

const typeImports = Object.entries(Object.groupBy(entries, ({ module }) => module)).map(
  ([module, group = []]) =>
    `import type { ${group.map(({ name }) => name).join(", ")} } from "../../../${module}/index.ts";`,
);
const guards = entries.map(({ name }) => `export declare function is${name}(data: unknown): data is ${name};`);
const declarations = `${header}${[...typeImports, "", ...guards].join("\n")}\n`;

const files = [
  { file: new URL("validators.js", outDir), contents: javascript },
  { file: new URL("validators.d.ts", outDir), contents: declarations },
];

const read = (file: URL) => {
  try {
    return readFileSync(file, "utf8");
  } catch {
    return undefined;
  }
};

if (process.argv.includes("--check")) {
  const stale = files.filter(({ file, contents }) => read(file) !== contents);
  for (const { file } of stale) {
    console.error(
      `Drift: ${file.pathname} doesn't match the response Schemas. Run \`pnpm validators\` and commit the result.`,
    );
  }
  process.exitCode = stale.length === 0 ? 0 : 1;
} else {
  for (const { file, contents } of files) writeFileSync(file, contents);
}
